let AI_SERVICE_URL = process.env.AI_SERVICE_URL || "http://127.0.0.1:8000";
if (AI_SERVICE_URL.includes("localhost")) {
    AI_SERVICE_URL = AI_SERVICE_URL.replace("localhost", "127.0.0.1");
}

/**
 * Strips markdown code fences (```lang ... ```) and prose to guarantee
 * only clean, executable source code is committed to GitHub.
 */
function extractCleanCode(content) {
    if (!content || typeof content !== "string") return content || "";
    const trimmed = content.trim();

    // Match code blocks ```[lang]?\n...\n```
    const codeBlockRegex = /```(?:[a-zA-Z0-9_\-\+]+)?\r?\n([\s\S]*?)```/g;
    const matches = [...trimmed.matchAll(codeBlockRegex)];

    if (matches.length > 0) {
        // Return the largest code block found
        const largest = matches.reduce((prev, curr) =>
            curr[1].length > prev[1].length ? curr : prev
        );
        return largest[1].trim();
    }

    // Direct fallback if fences on boundary
    if (trimmed.startsWith("```") && trimmed.endsWith("```")) {
        return trimmed.replace(/^```[a-zA-Z0-9_\-\+]*\r?\n/, "").replace(/```$/, "").trim();
    }

    return trimmed;
}

/**
 * Parses owner and repo name from GitHub URL or string.
 */
function parseGitHubUrl(repoUrl) {
    if (!repoUrl) {
        throw new Error("Repository URL is required");
    }

    let clean = repoUrl.trim().replace(/\/$/, "");

    // Handle SSH (git@github.com:owner/repo.git)
    if (clean.startsWith("git@github.com:")) {
        clean = clean.replace("git@github.com:", "");
    } else {
        // Handle https/http (https://github.com/owner/repo.git)
        clean = clean.replace(/^https?:\/\/(www\.)?github\.com\//, "");
    }

    if (clean.endsWith(".git")) {
        clean = clean.slice(0, -4);
    }

    const parts = clean.split("/").filter(Boolean);
    if (parts.length < 2) {
        throw new Error(`Invalid GitHub repository URL: "${repoUrl}". Expected format: https://github.com/owner/repo`);
    }

    return {
        owner: parts[parts.length - 2],
        repo: parts[parts.length - 1]
    };
}

/**
 * Standard headers for GitHub API requests.
 */
function getGitHubHeaders(token) {
    const headers = {
        "Accept": "application/vnd.github.v3+json",
        "User-Agent": "BugHunter-AI-Agent"
    };

    if (token) {
        headers["Authorization"] = `Bearer ${token.trim()}`;
    }

    return headers;
}

/**
 * Validates a GitHub Personal Access Token and returns user info.
 */
async function validateGitHubToken(token) {
    if (!token) {
        throw new Error("GitHub token is required");
    }

    const res = await fetch("https://api.github.com/user", {
        headers: getGitHubHeaders(token)
    });

    if (!res.ok) {
        const errorData = await res.json().catch(() => ({}));
        throw new Error(errorData.message || `GitHub authentication failed with status ${res.status}`);
    }

    const user = await res.json();
    return {
        valid: true,
        user: {
            login: user.login,
            name: user.name || user.login,
            avatarUrl: user.avatar_url,
            htmlUrl: user.html_url
        }
    };
}

/**
 * Generates PR summary with AI Service or markdown fallback.
 */
async function generatePRSummary({ issueDescription, analysis, patch, test, repoName }) {
    try {
        const response = await fetch(`${AI_SERVICE_URL}/generate-pr-description`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
                issue_description: issueDescription,
                analysis: analysis || null,
                patch: patch || null,
                test: test || null,
                repo_name: repoName || null
            }),
            signal: AbortSignal.timeout(60000)
        });

        if (response.ok) {
            const data = await response.json();
            return {
                title: data.title,
                description: data.description
            };
        }
    } catch (err) {
        console.warn("⚠️ AI PR description fallback triggered:", err.message);
    }

    // High quality deterministic fallback
    const title = `fix: resolve issue "${(issueDescription || 'Bug Fix').slice(0, 50)}"`;
    const description = `## 🐛 Bug Fix Summary
An autonomous fix was investigated and generated by **BugHunter AI**.

### 🔍 Issue Description
${issueDescription || 'No description provided.'}

${analysis ? `### 🔬 Root Cause Analysis\n${analysis}\n` : ''}

${patch ? `### 🛠️ Proposed Fix\n\`\`\`\n${patch}\n\`\`\`\n` : ''}

${test ? `### 🧪 Reproduction Test\n\`\`\`\n${test}\n\`\`\`\n` : ''}

---
*Created automatically by [BugHunter AI](https://github.com/kartikrastogi18/BigHunter-AI)*`;

    return { title, description };
}

/**
 * Creates or updates branch, commits files, and creates Pull Request.
 */
async function createPullRequest({
    token,
    repoUrl,
    baseBranch,
    branchName,
    title,
    body,
    files = []
}) {
    const activeToken = token || process.env.GITHUB_TOKEN;
    if (!activeToken) {
        throw new Error("GitHub token is required. Please provide a token with 'repo' scope.");
    }

    if (!repoUrl) {
        throw new Error("Repository URL is required.");
    }

    if (!files || files.length === 0) {
        throw new Error("At least one file (patch or test) is required to create a Pull Request.");
    }

    const { owner, repo } = parseGitHubUrl(repoUrl);
    const headers = getGitHubHeaders(activeToken);

    // 1. Validate user and permissions
    const userRes = await fetch("https://api.github.com/user", { headers });
    if (!userRes.ok) {
        throw new Error("Invalid GitHub token. Please verify your credentials.");
    }
    const currentUser = await userRes.json();

    // 2. Fetch repository info (default branch & permissions)
    const repoRes = await fetch(`https://api.github.com/repos/${owner}/${repo}`, { headers });
    if (!repoRes.ok) {
        const err = await repoRes.json().catch(() => ({}));
        throw new Error(`Failed to access repository ${owner}/${repo}: ${err.message || repoRes.statusText}`);
    }
    const repoData = await repoRes.json();
    const targetBaseBranch = baseBranch || repoData.default_branch || "main";

    // 3. Determine if we push directly or need a fork
    const canPush = repoData.permissions?.push === true;
    let pushOwner = owner;
    let pushRepo = repo;
    let isFork = false;

    if (!canPush) {
        console.log(`ℹ️ User does not have direct push access to ${owner}/${repo}. Forking repository to @${currentUser.login}...`);
        isFork = true;

        // Trigger fork
        const forkRes = await fetch(`https://api.github.com/repos/${owner}/${repo}/forks`, {
            method: "POST",
            headers
        });

        if (!forkRes.ok && forkRes.status !== 202) {
            const forkErr = await forkRes.json().catch(() => ({}));
            throw new Error(`Failed to fork repository: ${forkErr.message || forkRes.statusText}`);
        }

        pushOwner = currentUser.login;
        // Wait briefly for fork to register on GitHub
        await new Promise((resolve) => setTimeout(resolve, 3000));
    }

    // 4. Get the latest commit SHA of base branch
    const baseRefRes = await fetch(`https://api.github.com/repos/${owner}/${repo}/git/ref/heads/${targetBaseBranch}`, { headers });
    if (!baseRefRes.ok) {
        throw new Error(`Base branch '${targetBaseBranch}' not found on ${owner}/${repo}`);
    }
    const baseRefData = await baseRefRes.json();
    const baseSha = baseRefData.object.sha;

    // 5. Sanitize and create branch
    const timestamp = Date.now();
    const sanitizedBranch = (branchName || `bughunter/fix-${timestamp}`)
        .trim()
        .toLowerCase()
        .replace(/[^a-z0-9_\-\/]/g, "-")
        .replace(/-+/g, "-");

    console.log(`🌿 Creating branch '${sanitizedBranch}' on ${pushOwner}/${pushRepo}...`);

    // Check if branch already exists
    const checkBranchRes = await fetch(`https://api.github.com/repos/${pushOwner}/${pushRepo}/git/ref/heads/${sanitizedBranch}`, { headers });

    if (checkBranchRes.ok) {
        // Update existing branch ref
        await fetch(`https://api.github.com/repos/${pushOwner}/${pushRepo}/git/refs/heads/${sanitizedBranch}`, {
            method: "PATCH",
            headers: { ...headers, "Content-Type": "application/json" },
            body: JSON.stringify({ sha: baseSha, force: true })
        });
    } else {
        // Create new branch ref
        const createRefRes = await fetch(`https://api.github.com/repos/${pushOwner}/${pushRepo}/git/refs`, {
            method: "POST",
            headers: { ...headers, "Content-Type": "application/json" },
            body: JSON.stringify({
                ref: `refs/heads/${sanitizedBranch}`,
                sha: baseSha
            })
        });

        if (!createRefRes.ok) {
            const refErr = await createRefRes.json().catch(() => ({}));
            throw new Error(`Failed to create branch '${sanitizedBranch}': ${refErr.message || createRefRes.statusText}`);
        }
    }

    // 6. Commit all modified files to the branch
    console.log(`📦 Committing ${files.length} file(s) to branch '${sanitizedBranch}'...`);

    for (const file of files) {
        if (!file.path || file.content === undefined) continue;

        const cleanFilePath = file.path.replace(/^\/+/, "");

        // Check if file already exists in this branch to obtain SHA
        let existingFileSha = null;
        const fileRes = await fetch(
            `https://api.github.com/repos/${pushOwner}/${pushRepo}/contents/${cleanFilePath}?ref=${sanitizedBranch}`,
            { headers }
        );

        if (fileRes.ok) {
            const fileData = await fileRes.json();
            existingFileSha = fileData.sha;
        }

        const commitMessage = file.message || `fix(BugHunter): update ${cleanFilePath}`;
        const cleanContent = extractCleanCode(file.content);
        const base64Content = Buffer.from(cleanContent, "utf8").toString("base64");

        const putRes = await fetch(
            `https://api.github.com/repos/${pushOwner}/${pushRepo}/contents/${cleanFilePath}`,
            {
                method: "PUT",
                headers: { ...headers, "Content-Type": "application/json" },
                body: JSON.stringify({
                    message: commitMessage,
                    content: base64Content,
                    branch: sanitizedBranch,
                    ...(existingFileSha ? { sha: existingFileSha } : {})
                })
            }
        );

        if (!putRes.ok) {
            const putErr = await putRes.json().catch(() => ({}));
            throw new Error(`Failed to commit file '${cleanFilePath}': ${putErr.message || putRes.statusText}`);
        }
    }

    // 7. Open Pull Request on upstream repository
    const headRef = isFork ? `${pushOwner}:${sanitizedBranch}` : sanitizedBranch;
    const prTitle = title || `fix: autonomous bug resolution by BugHunter AI`;
    const prBody = body || `Automated bug fix generated and submitted by BugHunter AI.`;

    console.log(`🚀 Opening Pull Request from ${headRef} to ${owner}/${repo}:${targetBaseBranch}...`);

    const prRes = await fetch(`https://api.github.com/repos/${owner}/${repo}/pulls`, {
        method: "POST",
        headers: { ...headers, "Content-Type": "application/json" },
        body: JSON.stringify({
            title: prTitle,
            head: headRef,
            base: targetBaseBranch,
            body: prBody
        })
    });

    if (!prRes.ok) {
        const prErr = await prRes.json().catch(() => ({}));

        // Handle case where PR already exists for this branch
        if (prErr.errors && prErr.errors.some(e => e.message && e.message.includes("A pull request already exists"))) {
            const listPrs = await fetch(
                `https://api.github.com/repos/${owner}/${repo}/pulls?head=${encodeURIComponent(headRef)}&base=${targetBaseBranch}`,
                { headers }
            );
            if (listPrs.ok) {
                const existingPrs = await listPrs.json();
                if (existingPrs.length > 0) {
                    const pr = existingPrs[0];
                    return {
                        success: true,
                        alreadyExisted: true,
                        pullRequest: {
                            id: pr.id,
                            number: pr.number,
                            htmlUrl: pr.html_url,
                            title: pr.title,
                            state: pr.state,
                            base: targetBaseBranch,
                            head: headRef,
                            isFork,
                            forkRepo: isFork ? `${pushOwner}/${pushRepo}` : null
                        }
                    };
                }
            }
        }

        throw new Error(`Failed to create Pull Request: ${prErr.message || prRes.statusText}`);
    }

    const pr = await prRes.json();

    return {
        success: true,
        pullRequest: {
            id: pr.id,
            number: pr.number,
            htmlUrl: pr.html_url,
            title: pr.title,
            state: pr.state,
            base: targetBaseBranch,
            head: headRef,
            isFork,
            forkRepo: isFork ? `${pushOwner}/${pushRepo}` : null
        }
    };
}

module.exports = {
    parseGitHubUrl,
    validateGitHubToken,
    generatePRSummary,
    createPullRequest
};
